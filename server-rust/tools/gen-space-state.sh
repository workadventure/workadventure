#!/usr/bin/env sh
# Regenerates crates/core/src/space_state/generated.rs from the zod schema of the space state
# (libs/shared-utils/src/SpaceState/SpaceState.ts): zod -> JSON Schema with zod-to-json-schema (from the repository's
# node_modules), then JSON Schema -> Rust with cargo-typify (`cargo install cargo-typify --version 0.8.0`).
# The output is committed: building the server needs neither node nor libs/.
set -eu
here="$(cd "$(dirname "$0")" && pwd)"
repo="$(cd "$here/../.." && pwd)"
# The dev setup's node_modules holds Linux binaries (esbuild): node runs in a container, the main checkout mounted at
# its own path so that a worktree's relative node_modules symlink still resolves.
main="$(dirname "$(git -C "$repo" rev-parse --path-format=absolute --git-common-dir)")"
docker run --rm -v "$main:$main:ro" -w "$repo" node:22-slim \
    node_modules/.bin/tsx server-rust/tools/space-state-schema.ts > "$here/space-state.schema.json"
out="$here/../crates/core/src/space_state/generated.rs"
cargo typify --no-builder --additional-derive PartialEq --map-type ::std::collections::BTreeMap \
    -o "$out.tmp" "$here/space-state.schema.json"
{
    echo "// @generated by server-rust/tools/gen-space-state.sh from libs/shared-utils/src/SpaceState/SpaceState.ts."
    echo "// Do not edit: change the zod schema and run the script again."
    cat "$out.tmp"
} > "$out"
rm "$out.tmp"
# The repository's style (rustfmt.toml), so that a regeneration leaves no diff.
(cd "$here/.." && cargo fmt --all)
