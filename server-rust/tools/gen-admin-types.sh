#!/usr/bin/env sh
# Regenerates crates/server/src/admin_types/generated.rs from the zod schemas the pusher and the back read the
# admin's answers with (tools/admin-schemas.ts), through JSON Schema and cargo-typify (`cargo install cargo-typify
# --version 0.8.0`). The output is committed. Needs the repository's node_modules (host binaries); the dummy
# variables only satisfy the pusher's configuration check on import.
set -eu
here="$(cd "$(dirname "$0")" && pwd)"
repo="$(cd "$here/../.." && pwd)"
main="$(dirname "$(git -C "$repo" rev-parse --path-format=absolute --git-common-dir)")"
cd "$repo/play"
API_URL=back:50051 ICON_URL=http://icon MAP_STORAGE_API_TOKEN=x SECRET_KEY=x UPLOADER_URL=http://uploader \
    node "$main/node_modules/tsx/dist/cli.mjs" --tsconfig ../server-rust/tools/tsconfig.json ../server-rust/tools/admin-schemas.ts > "$here/admin-answers.schema.json"
out="$here/../crates/server/src/admin_types/generated.rs"
cargo typify --no-builder --additional-derive PartialEq --map-type ::std::collections::BTreeMap \
    -o "$out.tmp" "$here/admin-answers.schema.json"
{
    echo "// @generated by server-rust/tools/gen-admin-types.sh from the zod schemas of the admin's answers."
    echo "// Do not edit: change the zod schemas and run the script again."
    cat "$out.tmp"
} > "$out"
rm "$out.tmp"
(cd "$here/.." && cargo fmt --all)
