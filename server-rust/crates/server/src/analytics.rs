//! Analytics for the admin (A22, POST /api/analytics/events-batch), as the pusher's AnalyticsEventsQueue,
//! AnalyticsReportMessageHandler and AnalyticsTimedEventTracker, and the back's meeting rows (wa_core::meetings).
//!
//! On when the admin announces `api/analytics/events-batch: v1`. One bounded queue (the oldest event goes when
//! it is full), one batch per flush, retried on transient errors, a 422 re-sent event by event so that only the
//! invalid ones are lost. Property schemas are not checked here: the admin checks them again and refuses an
//! invalid event alone, which ends the same way (dropped) at the cost of a request.

use std::collections::{HashMap, VecDeque};
use std::sync::{Arc, LazyLock};
use std::time::{Duration, Instant};

use serde_json::{Map, Value, json};
use sha2::{Digest, Sha256};
use wa_proto::messages as pb;

use crate::admin_api::AdminApi;
use crate::config::Config;
use crate::redis_store::now_ms;
use crate::session::SessionInfo;
use crate::uploader::iso_at;

const MAX_ATTEMPTS: u32 = 4;
const MAX_EVENTS_PER_REPORT: usize = 100;
const MAX_PROPERTIES_BYTES: usize = 8 * 1024;
const MAX_OPEN_HANDLES: usize = 32;
const MAX_TIMESTAMP_MS: f64 = 8.64e15;
const END_REASONS: [&str; 5] = ["closed_by_client", "socket_closed", "join_failed", "pusher_shutdown", "pusher_crashed"];

#[derive(serde::Deserialize)]
#[serde(rename_all = "camelCase")]
struct IntervalFields {
    start: String,
    end: String,
    reason: String,
}

#[derive(serde::Deserialize)]
#[serde(rename_all = "camelCase")]
struct Definition {
    source: String,
    openable_by: Option<String>,
    opens_with: Option<String>,
    min_duration_ms: Option<u64>,
    interval_fields: Option<IntervalFields>,
}

/// AnalyticsEventCatalog.ts, generated by tools/gen-analytics-catalog.sh.
static CATALOG: LazyLock<HashMap<String, Definition>> =
    LazyLock::new(|| serde_json::from_str(include_str!("../analytics-catalog.json")).expect("analytics catalog"));

pub struct Analytics {
    url: String,
    authorization: String,
    http: reqwest::Client,
    instance: String,
    timeout: Duration,
    max_queue: usize,
    max_batch: usize,
    queue: parking_lot::Mutex<VecDeque<Value>>,
    /// One flush at a time.
    flushing: tokio::sync::Mutex<()>,
}

enum Failure {
    Invalid,
    Other,
}

fn jitter_ms() -> u64 {
    let nanos = std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).map_or(0, |d| d.subsec_nanos());
    50 + u64::from(nanos) % 201
}

impl Analytics {
    pub fn new(config: &Config, admin: &AdminApi, http: reqwest::Client) -> Option<Arc<Self>> {
        if !admin.has("api/analytics/events-batch") || admin.token.is_empty() {
            return None;
        }
        let num = |k: &str, d: u64| config.raw.get(k).and_then(|v| v.parse().ok()).filter(|n| *n > 0).unwrap_or(d);
        let raw = |k: &str| config.raw.get(k).filter(|v| !v.is_empty()).cloned();
        Some(Arc::new(Self {
            url: format!("{}/api/analytics/events-batch", admin.base.trim_end_matches('/')),
            authorization: format!("Bearer {}", admin.token),
            http,
            instance: raw("HOSTNAME").or_else(|| raw("SERVER_NAME")).unwrap_or_else(|| "pusher".into()),
            timeout: Duration::from_millis(num("ANALYTICS_TIMEOUT_MS", 2_000)),
            max_queue: num("ANALYTICS_MAX_QUEUE_SIZE", 10_000) as usize,
            max_batch: num("ANALYTICS_MAX_BATCH_SIZE", 1_000) as usize,
            queue: Default::default(),
            flushing: Default::default(),
        }))
    }

    /// Flushes every ANALYTICS_FLUSH_INTERVAL_MS.
    pub fn spawn(self: &Arc<Self>, config: &Config) {
        let every = config.raw.get("ANALYTICS_FLUSH_INTERVAL_MS").and_then(|v| v.parse().ok()).filter(|n| *n > 0).unwrap_or(10_000);
        let me = self.clone();
        tokio::spawn(async move {
            let mut tick = tokio::time::interval(Duration::from_millis(every));
            tick.tick().await;
            loop {
                tick.tick().await;
                me.flush(None).await;
            }
        });
    }

    pub fn enqueue(&self, event: Value) {
        let mut q = self.queue.lock();
        if q.len() >= self.max_queue {
            q.pop_front();
            tracing::warn!("analytics queue full: the oldest event is dropped");
        }
        q.push_back(event);
    }

    pub fn len(&self) -> usize {
        self.queue.lock().len()
    }

    pub fn is_empty(&self) -> bool {
        self.len() == 0
    }

    /// Sends the oldest batch, if any.
    pub async fn flush(&self, deadline: Option<Instant>) {
        let Ok(_one) = self.flushing.try_lock() else { return };
        let events: Vec<Value> = {
            let mut q = self.queue.lock();
            let n = q.len().min(self.max_batch);
            q.drain(..n).collect()
        };
        if events.is_empty() {
            return;
        }
        let sent_at = iso_at(now_ms());
        let n = events.len();
        match self.send(&sent_at, &events, deadline).await {
            Ok(()) => {}
            Err(Failure::Invalid) if n > 1 => self.one_by_one(&sent_at, events, deadline).await,
            Err(_) => tracing::warn!(events = n, "analytics batch dropped after failed sends"),
        }
    }

    /// After a 422 on a batch: each event alone, the invalid ones dropped, the rest dropped on a hard failure.
    async fn one_by_one(&self, sent_at: &str, events: Vec<Value>, deadline: Option<Instant>) {
        let total = events.len();
        for (i, e) in events.into_iter().enumerate() {
            if deadline.is_some_and(|d| Instant::now() >= d) {
                tracing::warn!(events = total - i, "analytics drain ran out of time");
                return;
            }
            match self.send(sent_at, std::slice::from_ref(&e), deadline).await {
                Ok(()) => {}
                Err(Failure::Invalid) => tracing::warn!(event = %e["eventName"], "analytics event refused by the admin"),
                Err(Failure::Other) => {
                    tracing::warn!(events = total - i, "analytics events dropped after failed sends");
                    return;
                }
            }
        }
    }

    async fn send(&self, sent_at: &str, events: &[Value], deadline: Option<Instant>) -> Result<(), Failure> {
        let body = json!({ "schemaVersion": 1, "sentAt": sent_at, "pusherInstanceId": self.instance, "events": events });
        let mut last = Failure::Other;
        for attempt in 0..MAX_ATTEMPTS {
            let mut timeout = self.timeout;
            if let Some(d) = deadline {
                let left = d.saturating_duration_since(Instant::now());
                if left.is_zero() {
                    break;
                }
                timeout = timeout.min(left).max(Duration::from_millis(1));
            }
            let sent = self.http.post(&self.url).header("Authorization", &self.authorization).json(&body).timeout(timeout).send().await;
            match sent.map(|r| r.status().as_u16()) {
                Ok(s) if (200..300).contains(&s) => return Ok(()),
                Ok(422) => return Err(Failure::Invalid),
                // Client errors are final, except a timeout and a rate limit.
                Ok(s) if (400..500).contains(&s) && s != 408 && s != 429 => return Err(Failure::Other),
                _ => last = Failure::Other,
            }
            if attempt + 1 < MAX_ATTEMPTS {
                let delay = Duration::from_millis((250u64 << attempt).min(5_000) + jitter_ms());
                if deadline.is_some_and(|d| Instant::now() + delay >= d) {
                    break;
                }
                tokio::time::sleep(delay).await;
            }
        }
        Err(last)
    }

    /// On SIGTERM: sends what is queued, for at most `timeout` (DRAIN_TIMEOUT_MS).
    pub async fn drain(&self, timeout: Duration) {
        let deadline = Instant::now() + timeout;
        while !self.is_empty() && Instant::now() < deadline {
            let before = self.len();
            self.flush(Some(deadline)).await;
            if self.len() == before {
                tokio::time::sleep(Duration::from_millis(50)).await;
            }
        }
    }
}

/// The connection's part of an event (SocketData), and the checks every pusher event goes through.
pub struct Context<'a> {
    pub info: &'a SessionInfo,
    pub user_id: Option<i32>,
    pub space_user_id: String,
}

impl Context<'_> {
    fn envelope(&self, name: &str, source: &str, client_ms: u64, event_id: String, properties: Value) -> Option<Value> {
        let info = self.info;
        if !info.analytics_enabled {
            return None;
        }
        if info.user_uuid.is_empty() || self.space_user_id.is_empty() || info.world.is_empty() || info.room_id.is_empty() {
            tracing::warn!(event = name, "analytics event without its context dropped");
            return None;
        }
        if serde_json::to_string(&properties).map_or(usize::MAX, |s| s.len()) > MAX_PROPERTIES_BYTES {
            tracing::warn!(event = name, "analytics event properties over 8 KiB dropped");
            return None;
        }
        Some(json!({
            "eventName": name, "source": source,
            "clientEventTime": iso_at(client_ms), "pusherReceivedAt": iso_at(now_ms()),
            "eventId": event_id, "userUuid": info.user_uuid, "userId": self.user_id, "spaceUserId": self.space_user_id,
            "clientIp": Some(&info.ip_address).filter(|ip| !ip.is_empty()), "world": info.world, "roomId": info.room_id,
            "tabId": info.tab_id, "tags": info.tags, "properties": properties,
        }))
    }
}

/// A time a client sent as a number, if a Date can hold it.
fn client_time(ms: u64) -> Option<u64> {
    ((ms as f64) <= MAX_TIMESTAMP_MS).then_some(ms)
}

struct Open {
    handle: String,
    event_name: String,
    started_ms: u64,
    properties: Map<String, Value>,
}

/// A connection's open intervals (AnalyticsTimedEventTracker), its session among them under "connection".
#[derive(Default)]
pub struct Timed {
    open: Vec<Open>,
    pub last_activity_ms: u64,
}

impl Timed {
    fn open(&mut self, a: &Analytics, ctx: &Context, handle: &str, event_name: &str, properties: Map<String, Value>, started_ms: u64) -> bool {
        let Some(def) = CATALOG.get(event_name) else { return false };
        if self.open.iter().any(|o| o.handle == handle) || self.open.len() >= MAX_OPEN_HANDLES {
            return false;
        }
        if let Some(opening) = &def.opens_with {
            let start = def.interval_fields.as_ref().map_or("startedAt", |f| f.start.as_str());
            let mut p = properties.clone();
            p.insert(start.into(), iso_at(started_ms).into());
            let id = format!("{}:{handle}:opened:{started_ms}", ctx.info.tab_id);
            a.enqueue_opt(ctx.envelope(opening, "pusher", started_ms, id, Value::Object(p)));
        }
        self.open.push(Open { handle: handle.into(), event_name: event_name.into(), started_ms, properties });
        true
    }

    /// Opens the connection's session (on roomJoined), once.
    pub fn connected(&mut self, a: &Analytics, ctx: &Context, at_ms: u64) {
        if !self.open.iter().any(|o| o.handle == "connection") {
            let p = Map::from_iter([("connectionId".to_owned(), Value::from(ctx.info.tab_id.clone()))]);
            self.open(a, ctx, "connection", "user.disconnected", p, at_ms);
        }
    }

    fn close(&mut self, a: &Analytics, ctx: &Context, handle: &str, reason: &str) {
        let Some(i) = self.open.iter().position(|o| o.handle == handle) else { return };
        let o = self.open.remove(i);
        let Some(def) = CATALOG.get(&o.event_name) else { return };
        let now = now_ms();
        let ended_ms = if reason == "socket_closed" { now.min(self.last_activity_ms).max(o.started_ms) } else { now };
        let elapsed = ended_ms - o.started_ms;
        if elapsed < def.min_duration_ms.unwrap_or(1_000) {
            return;
        }
        let (start, end, why) =
            def.interval_fields.as_ref().map_or(("startedAt", "endedAt", "endReason"), |f| (f.start.as_str(), f.end.as_str(), f.reason.as_str()));
        let duration = if o.event_name == "user.disconnected" { json!((elapsed as f64 / 1000.0).round() as u64) } else { json!(elapsed as f64 / 1000.0) };
        let mut p = o.properties;
        p.insert(start.into(), iso_at(o.started_ms).into());
        p.insert(end.into(), iso_at(ended_ms).into());
        p.insert("durationSeconds".into(), duration);
        p.insert(why.into(), reason.into());
        let id = format!("{}:{handle}:{ended_ms}", ctx.info.tab_id);
        a.enqueue_opt(ctx.envelope(&o.event_name, "pusher", ended_ms, id, Value::Object(p)));
    }

    /// Ends every interval, the session last so that the others end within it.
    pub fn close_all(&mut self, a: &Analytics, ctx: &Context, reason: &str) {
        let handles: Vec<String> = self.open.iter().map(|o| o.handle.clone()).filter(|h| h != "connection").collect();
        for h in handles.iter().map(String::as_str).chain(["connection"]) {
            self.close(a, ctx, h, reason);
        }
    }

    /// analyticsEventReportMessage (processAnalyticsReportMessage).
    pub fn report(&mut self, a: &Analytics, ctx: &Context, report: pb::AnalyticsEventReportMessage) {
        if report.events.len() > MAX_EVENTS_PER_REPORT {
            tracing::warn!(events = report.events.len(), "analytics report over 100 events dropped");
            return;
        }
        for e in report.events {
            if e.source != "front" && e.source != "media" {
                continue;
            }
            let properties = e.properties.as_ref().map_or(Value::Object(Map::new()), crate::wire::json_from);
            match e.event_name.as_str() {
                "timed_event.open" => {
                    let (Some(handle), Some(name)) = (properties["handle"].as_str(), properties["eventName"].as_str()) else { continue };
                    let client_openable = CATALOG.get(name).is_some_and(|d| d.openable_by.as_deref() == Some("client"));
                    let inner = properties.get("properties").cloned().unwrap_or(Value::Object(Map::new()));
                    let fits = serde_json::to_string(&inner).is_ok_and(|s| s.len() <= MAX_PROPERTIES_BYTES);
                    if let (true, true, true, Value::Object(inner)) = (client_openable, fits, (1..=255).contains(&handle.len()), inner) {
                        self.open(a, ctx, handle, name, inner, now_ms());
                    }
                }
                "timed_event.close" => {
                    let Some(handle) = properties["handle"].as_str() else { continue };
                    let reason = properties["endReason"].as_str().filter(|r| END_REASONS.contains(r)).unwrap_or("closed_by_client");
                    self.close(a, ctx, handle, reason);
                }
                name => {
                    // A name the catalog does not know, or one the server signs: dropped.
                    let ok = CATALOG.get(name).is_some_and(|d| d.source == e.source)
                        && e.event_id.len() <= 255
                        && properties.is_object()
                        && client_time(e.client_event_time_ms).is_some();
                    if ok {
                        a.enqueue_opt(ctx.envelope(name, &e.source, e.client_event_time_ms, e.event_id, properties));
                    }
                }
            }
        }
    }
}

impl Analytics {
    fn enqueue_opt(&self, event: Option<Value>) {
        if let Some(e) = event {
            self.enqueue(e);
        }
    }

    /// videoQualityReportMessage: one media.video_quality.sample per sample, for the spaces the socket is in.
    pub fn video_quality(&self, ctx: &Context, report: pb::VideoQualityReportMessage, in_space: impl Fn(&str) -> bool) {
        for s in report.samples {
            if let Some(p) = video_sample(&s).filter(|_| in_space(&s.space_name)) {
                let id = format!("{}:{}:{}", ctx.info.user_uuid, s.stream_id, s.sample_seq.unwrap_or(s.client_event_time_ms));
                self.enqueue_opt(ctx.envelope("media.video_quality.sample", "pusher", s.client_event_time_ms, id, p));
            }
        }
    }

    /// The back's meeting rows.
    pub fn meeting_rows(&self, world: &str, rows: Vec<wa_core::meetings::Row>) {
        for r in rows {
            let at = iso_at(r.at_ms);
            let id: String = Sha256::digest(r.id_parts.as_bytes()).iter().map(|b| format!("{b:02x}")).collect();
            let m = r.member.as_ref();
            self.enqueue(json!({
                "eventName": r.event_name, "source": "pusher", "clientEventTime": at, "pusherReceivedAt": at, "eventId": id,
                "userUuid": m.map_or("", |m| m.uuid.as_str()), "userId": null, "spaceUserId": m.map_or("", |m| m.space_user_id.as_str()),
                "clientIp": null, "world": world, "roomId": r.room_id, "tabId": null,
                "tags": m.map_or(&[][..], |m| &m.tags[..]), "properties": r.properties,
            }));
        }
    }
}

fn plausible(v: Option<f64>, max: f64) -> Value {
    v.filter(|v| v.is_finite() && (0.0..=max).contains(v)).map_or(Value::Null, Value::from)
}

fn counter<T: Into<f64> + Copy>(v: Option<T>) -> Value {
    v.map(Into::into).filter(|v: &f64| v.is_finite() && *v >= 0.0).map_or(Value::Null, Value::from)
}

/// The sample's properties, None when it cannot be one (toVideoQualityProperties).
fn video_sample(s: &pb::VideoQualitySampleMessage) -> Option<Value> {
    use pb::{VideoQualityLimitationReason as L, VideoQualityRelayProtocol as R, VideoQualityStreamCategory as C, VideoQualityStreamDirection as D, VideoQualityTransportType as T};
    if s.stream_id.is_empty() || s.space_name.is_empty() || client_time(s.client_event_time_ms).is_none() {
        return None;
    }
    let category = match C::try_from(s.stream_category).ok()? {
        C::Video => "video",
        C::ScreenSharing => "screenSharing",
    };
    let transport = match T::try_from(s.transport_type).ok()? {
        T::P2p => "P2P",
        T::Livekit => "SFU",
    };
    if ![s.fps, s.jitter, s.bandwidth_bytes_per_second, f64::from(s.frame_width), f64::from(s.frame_height)].iter().all(|v| v.is_finite()) {
        return None;
    }
    let outbound = s.direction == D::Outbound as i32;
    let out = |v: Value| if outbound { v } else { Value::Null };
    let window = s.window_seconds.filter(|w| !outbound && w.is_finite() && *w > 0.0 && *w <= 300.0);
    let play = |v: Value| if window.is_some() { v } else { Value::Null };
    let opt = |v: &Option<String>| v.clone().map_or(Value::Null, Value::from);
    let nonempty = |v: &str| if v.is_empty() { Value::Null } else { v.into() };
    Some(json!({
        "streamId": s.stream_id, "connectionId": opt(&s.connection_id), "sessionId": opt(&s.session_id),
        "remoteUserUuid": opt(&s.remote_user_uuid), "remoteSpaceUserId": nonempty(&s.remote_space_user_id),
        "spaceName": s.space_name, "streamCategory": category, "transportType": transport,
        "direction": if outbound { "outbound" } else { "inbound" }, "relay": s.relay,
        "relayProtocol": s.relay_protocol.and_then(|r| R::try_from(r).ok()).map(|r| match r { R::Udp => "udp", R::Tcp => "tcp", R::Tls => "tls" }),
        "livekitServerUrl": opt(&s.livekit_server_url), "livekitRegion": s.livekit_region.as_deref().map_or(Value::Null, nonempty),
        "fps": s.fps, "fpsStdDev": s.fps_std_dev.filter(|v| v.is_finite()), "jitter": s.jitter,
        "bandwidthBytesPerSecond": s.bandwidth_bytes_per_second,
        "frameWidth": f64::from(s.frame_width).round(), "frameHeight": f64::from(s.frame_height).round(),
        "mimeType": opt(&s.mime_type),
        "qualityLimitationReason": out(s.quality_limitation_reason.and_then(|r| L::try_from(r).ok()).map_or(Value::Null, |r| match r {
            L::None => "none", L::Cpu => "cpu", L::Bandwidth => "bandwidth", L::Other => "other" }.into())),
        "encoderImplementation": out(opt(&s.encoder_implementation)),
        "sampleSeq": s.sample_seq,
        "windowSeconds": window,
        "framesDecoded": play(counter(s.frames_decoded)), "framesDropped": play(counter(s.frames_dropped)),
        "freezeCount": play(counter(s.freeze_count)), "freezeSeconds": play(counter(s.freeze_seconds)),
        "pauseCount": play(counter(s.pause_count)), "pauseSeconds": play(counter(s.pause_seconds)),
        "interFrameDelaySumSeconds": play(counter(s.inter_frame_delay_sum_seconds)),
        "interFrameDelaySquaredSumSeconds": play(counter(s.inter_frame_delay_squared_sum_seconds)),
        "decodeSeconds": play(counter(s.decode_seconds)),
        "packetsReceived": play(counter(s.packets_received)), "packetsLost": play(counter(s.packets_lost)),
        "roundTripTimeMs": if outbound { Value::Null } else { plausible(s.round_trip_time_ms, 60_000.0) },
        "captureFps": out(plausible(s.capture_fps, 240.0)), "captureTargetFps": out(plausible(s.capture_target_fps, 240.0)),
        "encodeMsPerFrame": out(plausible(s.encode_ms_per_frame, 10_000.0)),
        "cpuLimitedRatio": out(plausible(s.cpu_limited_ratio, 1.0)), "bandwidthLimitedRatio": out(plausible(s.bandwidth_limited_ratio, 1.0)),
        "uploadRoundTripTimeMs": out(plausible(s.upload_round_trip_time_ms, 60_000.0)), "uploadLossRatio": out(plausible(s.upload_loss_ratio, 1.0)),
        "availableOutgoingBitrate": out(plausible(s.available_outgoing_bitrate, 10_000_000_000.0)),
    }))
}
