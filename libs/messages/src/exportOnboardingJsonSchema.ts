import fs from "fs";
import { fileURLToPath } from "url";
import { zodToJsonSchema } from "zod-to-json-schema";
import {
  BuiltinOnboardingAnchor,
  BuiltinTourId,
  OnboardingAnchor,
  OnboardingAnchorArea,
  OnboardingData,
  OnboardingText,
  OnboardingTipGroup,
} from "./JsonMessages/OnboardingData";

/**
 * Publishes the onboarding config of a world as JSON Schema, at
 * https://docs.workadventu.re/docs/schema/onboarding.json. Self-hosters check their file with it, and the
 * SaaS admin checks what its editor saves. Its editor reads the anchors and their areas, and the built-in tours (all
 * with their names) in `$defs`.
 */
const { $schema: _, ...schema } = zodToJsonSchema(OnboardingData, {
  definitions: {
    OnboardingAnchor,
    BuiltinOnboardingAnchor,
    OnboardingAnchorArea,
    OnboardingText,
    BuiltinTourId,
    OnboardingTipGroup,
  },
  definitionPath: "$defs",
}) as Record<string, unknown>;

const jsonSchema = {
  $schema: "https://json-schema.org/draft/2020-12/schema",
  $id: "https://docs.workadventu.re/docs/schema/onboarding.json",
  title: "WorkAdventure onboarding",
  ...schema,
};

fs.writeFileSync(
  fileURLToPath(
    new URL("../../../docs/schema/onboarding.json", import.meta.url),
  ),
  JSON.stringify(jsonSchema, null, 2) + "\n",
);

/**
 * The anchor and group tables of the self-hosting guide, written from the labels of the schema so that they cannot
 * drift from it. CI checks that the file is up to date.
 */
const guide = fileURLToPath(
  new URL("../../../docs/others/self-hosting/onboarding.md", import.meta.url),
);

/** Replaces what lies between the `<name>:start` and `<name>:end` markers of the guide. */
function writeBetweenMarkers(text: string, name: string, content: string) {
  const start = `<!-- ${name}:start: generated by "npm run export-json-schema" in libs/messages -->`;
  const end = `<!-- ${name}:end -->`;
  const from = text.indexOf(start);
  const to = text.indexOf(end);
  if (from === -1 || to < from) {
    // A doc edit that deletes a marker fails the CI step instead of leaving the table out of date.
    throw new Error(`${guide}: the ${name} markers are missing`);
  }
  return `${text.slice(0, from + start.length)}\n\n${content}\n\n${text.slice(to)}`;
}

const anchorTables = OnboardingAnchorArea.options
  .map((area) =>
    [
      `**${area.description}** (\`${area.value}\`)`,
      "",
      "| Anchor | |",
      "|---|---|",
      ...BuiltinOnboardingAnchor.options
        .filter((anchor) => anchor.value.startsWith(`${area.value}.`))
        .map((anchor) => `| \`${anchor.value}\` | ${anchor.description} |`),
    ].join("\n"),
  )
  .join("\n\n");
const groupTable = [
  "| Group | |",
  "|---|---|",
  ...OnboardingTipGroup.options.map(
    (group) => `| \`${group.value}\` | ${group.description} |`,
  ),
].join("\n");

fs.writeFileSync(
  guide,
  writeBetweenMarkers(
    writeBetweenMarkers(
      fs.readFileSync(guide, "utf8"),
      "anchors",
      anchorTables,
    ),
    "groups",
    groupTable,
  ),
);
