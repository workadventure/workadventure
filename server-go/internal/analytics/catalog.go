// EndReason is one of TIMED_EVENT_END_REASONS; an older or unknown one reads as closed_by_client.
func EndReason(r string) string {
	switch r {
	case "closed_by_client", "socket_closed", "join_failed", "pusher_shutdown", "pusher_crashed":
		return r
	}
	return "closed_by_client"
}

// MaxEventsPerReport is the most events one report message may carry; more, and the whole message is dropped.
const MaxEventsPerReport = 100

// MaxPropertiesBytes bounds the JSON of an event's properties.
const MaxPropertiesBytes = 8 * 1024

// FromClient tells whether a client may report this event (the envelope of the catalog): a known name, the source
// the catalog gives it, an event id of 1 to 255 characters and a plausible time. "media" is a client source no
// event carries yet.
func FromClient(name, source, eventID string, clientEventTimeMs uint64) bool {
	want, ok := catalog[name]
	return ok && (source == "front" || source == "media") && source == want && len(eventID) >= 1 && len(eventID) <= 255 &&
		clientEventTimeMs <= 8.64e15
}
