// Timed is a timed event (timedEvent()): the pusher measures the interval and writes one row when it closes.
type Timed struct {
	ByClient           bool   // openableBy "client": timed_event.open may open it
	OpensWith          string // an event emitted when it opens
	Start, End, Reason string // its interval fields
	MinDurationMs      int64  // shorter intervals are dropped
}

